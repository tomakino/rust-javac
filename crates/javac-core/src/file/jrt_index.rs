//! A package-oriented index into the jrt: filesystem.
//!
//! <p><b>This is NOT part of any supported API.
//! If you write code that depends on this, you do so at your own risk.
//! This code and its internal interfaces are subject to change or
//! deletion without notice.</b>
//!
//! PORTING_RULES (S3a):
//! * the jrt: FileSystem does not exist without a JVM, so the index is built from the
//!   registered javac-jimage adapter over `<java.home>/lib/modules`: the module list
//!   (`JImage::modules`) and the sorted resource names `<module>/<path>` stand in for
//!   a walk of `/modules` and `/packages`.  A Java `Path` value in an Entry is represented as the
//!   jrt-style textual path `/modules/<module>/<relative path>` (javac-fs Path).
//! * the JDK home is injected (java.home is a JVM system property); the P6 launcher passes it,
//!   like platform.JDKPlatformProvider (registered deviation).
//! * java.lang.ref.SoftReference<Entry> -> plain cached entries (memory-management detail with
//!   no observable behaviour without GC pressure; registered).
//! * getCtInfo reads the ResourceBundle `com.sun.tools.javac.resources.ct` (the ct.properties
//!   hidden/proprietary/minProfile attributes).  That resource is NOT generated by xtask yet and
//!   java.util.ResourceBundle is not ported: getCtInfo returns CtSym::empty() (the upstream
//!   missing-key result) for every package until the resource lands (TODO resources,
//!   reported).  No substitute attributes are invented.
//! * getSharedInstance()/instance(Context) cache the index per thread/context; because the
//!   JDK home cannot be discovered from a Context, both take the injected home and then behave
//!   like the upstream caches.
//! * isInJRT(FileObject) tests `fo instanceof PathFileObject && path.getFileSystem() == jrtfs`;
//!   without a jrt FileSystem the port uses the JRTFileObject construction marker of the concrete
//!   PathFileObject parameter (no Rust downcast from FileObject; no upstream caller yet).

use std::cell::RefCell;
use std::collections::HashMap;
use std::fmt;
use std::path::PathBuf;
use std::rc::Rc;

use javac_fs::Path as FsPath;
use javac_jimage::JImage;
use javac_strings::JavaString;

use crate::file::path_file_object::PathFileObject;
use crate::file::relative_path::RelativeDirectory;
use crate::util::context::Context;

/// Java: jrtfs.getPath("/modules").
const MODULES_PATH: &str = "/modules";

thread_local! {
    // Java: private static JRTIndex sharedInstance;
    static SHARED_INSTANCE: RefCell<Option<Rc<JRTIndex>>> = const { RefCell::new(None) };
}

/// A package-oriented index into the jrt: filesystem.
pub struct JRTIndex {
    /// Java: private final FileSystem jrtfs; — replaced by the javac-jimage adapter.
    image: JImage,

    /// The module names in image order (Java: the /modules child order).
    modules: Vec<String>,

    /// Module name -> the module-relative resource paths ("java/lang/Object.class").
    module_resources: HashMap<String, Vec<String>>,

    /// Java: private final Map<RelativeDirectory, SoftReference<Entry>> entries;
    entries: RefCell<HashMap<RelativeDirectory, Rc<Entry>>>,
}

/// Java: class JRTIndex.Entry — cached info about a package directory.
pub(crate) struct Entry {
    /// Java: final Map<String, Path> files; — LinkedHashMap order kept by the Vec.
    pub(crate) files: Vec<(String, FsPath)>,

    /// Java: final Set<RelativeDirectory> subdirs; — LinkedHashSet order kept by the Vec.
    pub(crate) subdirs: Vec<RelativeDirectory>,

    /// Java: final CtSym ctSym;
    pub(crate) ct_sym: CtSym,
}

impl Entry {
    fn new() -> Entry {
        Entry {
            files: Vec::new(),
            subdirs: Vec::new(),
            ct_sym: CtSym::empty(),
        }
    }

    /// Java: files.get(name) / files.put(name, path) with the LinkedHashMap overwrite rule.
    ///
    /// TODO(S3c): get_file is used by JavacFileManager once that lands.
    #[allow(dead_code)]
    pub(crate) fn get_file(&self, name: &str) -> Option<&FsPath> {
        self.files
            .iter()
            .find(|(file_name, _)| file_name == name)
            .map(|(_, path)| path)
    }

    fn put_file(&mut self, name: &str, path: FsPath) {
        if let Some(entry) = self
            .files
            .iter_mut()
            .find(|(file_name, _)| file_name == name)
        {
            entry.1 = path;
        } else {
            self.files.push((name.to_string(), path));
        }
    }

    fn add_subdir(&mut self, subdir: RelativeDirectory) {
        if !self.subdirs.contains(&subdir) {
            self.subdirs.push(subdir);
        }
    }
}

/// Java: public static class JRTIndex.CtSym — the info that used to be in ct.sym for a package.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CtSym {
    /// The classes in this package are internal and not visible.
    pub hidden: bool,
    /// The classes in this package are proprietary and will generate a warning.
    pub proprietary: bool,
    /// The minimum profile in which classes in this package are available (null -> None).
    pub min_profile: Option<JavaString>,
}

impl CtSym {
    /// Java: static final CtSym EMPTY = new CtSym(false, false, null);
    ///
    /// PORTING_RULES: JavaString is not const-constructible in Rust, so the Java constant
    /// becomes this constructor (registered).
    pub fn empty() -> CtSym {
        CtSym {
            hidden: false,
            proprietary: false,
            min_profile: None,
        }
    }
}

impl fmt::Display for CtSym {
    /// Java: public String toString() — "CtSym[hidden,proprietary,minProfile]".
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("CtSym[")?;
        let mut need_sep = false;
        if self.hidden {
            f.write_str("hidden")?;
            need_sep = true;
        }
        if self.proprietary {
            if need_sep {
                f.write_str(",")?;
            }
            f.write_str("proprietary")?;
            need_sep = true;
        }
        if let Some(min_profile) = &self.min_profile {
            if need_sep {
                f.write_str(",")?;
            }
            f.write_str(&min_profile.to_string_lossy())?;
        }
        f.write_str("]")
    }
}

impl JRTIndex {
    /// Java: private JRTIndex() throws IOException — opens the jrt: file system.
    ///
    /// PORTING_RULES: the jrt: FileSystem is simulated by javac-jimage over the injected JDK
    /// home (see the file header).
    pub fn open(java_home: &FsPath) -> Result<JRTIndex, javac_jimage::Error> {
        let modules_file = java_home.as_path().join("lib").join("modules");
        let image = JImage::open(&modules_file)?;
        let modules = image.modules().to_vec();
        let mut module_resources: HashMap<String, Vec<String>> = HashMap::new();
        for resource in image.resources() {
            if let Some((module, relative)) = resource.split_once('/') {
                module_resources
                    .entry(module.to_string())
                    .or_default()
                    .push(relative.to_string());
            }
        }
        Ok(JRTIndex {
            image,
            modules,
            module_resources,
            entries: RefCell::new(HashMap::new()),
        })
    }

    /// Read an image resource by its jrt: path ("/modules/<module>/<resource>").
    ///
    /// Adapter: the jrt: filesystem read is expressed through the javac-jimage
    /// image handle (registered adapter).
    ///
    /// # Arguments
    ///   - path: the jrt resource path.
    ///
    /// # Returns
    ///   - the resource bytes, if the entry exists.
    ///
    /// # Panics
    ///   - none.
    pub fn get_resource(&self, path: &FsPath) -> Option<Vec<u8>> {
        let path_text = path.to_java_string().to_string().replace('\\', "/");
        let name = path_text.strip_prefix("/modules/").unwrap_or(&path_text);
        self.image.find_resource(name)
    }


    /// Java: public static boolean isAvailable() — whether the jrt: file system exists.
    pub fn is_available(java_home: &FsPath) -> bool {
        JRTIndex::open(java_home).is_ok()
    }

    /// Java: public synchronized static JRTIndex getSharedInstance().
    ///
    /// PORTING_RULES: the shared cache is per thread (a JVM-wide static has no Rust
    /// counterpart without a global lock and Rc is not Send); the JDK home is the injected
    /// argument (the first home wins, like the upstream single static instance).
    pub fn get_shared_instance(java_home: &FsPath) -> Rc<JRTIndex> {
        SHARED_INSTANCE.with(|slot| {
            let mut slot = slot.borrow_mut();
            match slot.as_ref() {
                Some(instance) => instance.clone(),
                None => {
                    let instance = Rc::new(JRTIndex::open(java_home).unwrap_or_else(|_| {
                        panic!("java.io.UncheckedIOException: cannot open the jrt: image")
                    }));
                    *slot = Some(instance.clone());
                    instance
                }
            }
        })
    }

    /// Java: public static JRTIndex instance(Context context).
    ///
    /// PORTING_RULES: the JDK home is injected (see the file header).
    pub fn instance(context: &mut Context, java_home: &FsPath) -> Rc<JRTIndex> {
        if let Some(instance) = context.get::<JRTIndex>() {
            return instance;
        }
        let instance = Rc::new(JRTIndex::open(java_home).unwrap_or_else(|_| {
            panic!("java.io.UncheckedIOException: cannot open the jrt: image")
        }));
        context.put(instance.clone());
        instance
    }

    /// Java: public CtSym getCtSym(CharSequence packageName) throws IOException.
    pub fn get_ct_sym(&self, package_name: &JavaString) -> Result<CtSym, javac_jimage::Error> {
        Ok(self
            .get_entry(&RelativeDirectory::for_package(package_name))?
            .ct_sym
            .clone())
    }

    /// Java: synchronized Entry getEntry(RelativeDirectory rd) throws IOException.
    pub(crate) fn get_entry(
        &self,
        rd: &RelativeDirectory,
    ) -> Result<Rc<Entry>, javac_jimage::Error> {
        if let Some(entry) = self.entries.borrow().get(rd) {
            return Ok(entry.clone());
        }
        let mut entry = Entry::new();
        let rd_path = rd.as_relative_path().get_path();
        if rd_path.is_empty() {
            // Java: dir = jrtfs.getPath("/modules"); every module directory is visited.
            for module in &self.modules {
                if let Some(resources) = self.module_resources.get(module) {
                    for relative in resources {
                        JRTIndex::add_entry(rd, module, relative, relative, &mut entry);
                    }
                }
            }
        } else {
            // Java: dir = /packages/<package>; every module of the package is visited, then
            // rd.resolveAgainst(module) is listed.
            let package_path = rd_path.to_string_lossy();
            let package_name = package_path.trim_end_matches('/').replace('/', ".");
            for module in self.image.modules_of_package(&package_name)? {
                if let Some(resources) = self.module_resources.get(&module) {
                    for relative in resources {
                        if let Some(rest) = relative.strip_prefix(&package_path) {
                            // Java: the package directory path has no trailing
                            // separator; strip the separator of the resolved
                            // directory before classifying the entry.
                            let rest = rest.strip_prefix('/').unwrap_or(rest);
                            JRTIndex::add_entry(rd, &module, rest, relative, &mut entry);
                        }
                    }
                }
            }
        }
        entry.ct_sym = JRTIndex::get_ct_info(rd);
        let entry = Rc::new(entry);
        self.entries.borrow_mut().insert(rd.clone(), entry.clone());
        Ok(entry)
    }

    /// The listing of one directory entry: a subdirectory of the listed directory, or a file
    /// whose jrt path is `/modules/<module>/<module_relative>`.
    fn add_entry(
        rd: &RelativeDirectory,
        module: &str,
        relative_to_dir: &str,
        module_relative: &str,
        entry: &mut Entry,
    ) {
        match relative_to_dir.split_once('/') {
            Some((first, _)) => {
                entry.add_subdir(RelativeDirectory::with_parent(rd, &JavaString::from(first)));
            }
            None => {
                let path = FsPath::from_path_buf(PathBuf::from(format!(
                    "{MODULES_PATH}/{module}/{module_relative}"
                )));
                entry.put_file(relative_to_dir, path);
            }
        }
    }

    /// Java: private CtSym getCtInfo(RelativeDirectory dir).
    ///
    /// TODO(resources): the upstream reads the ResourceBundle
    /// "com.sun.tools.javac.resources.ct" (hidden/proprietary/minProfile attributes).  The
    /// resource is not generated by xtask yet and java.util.ResourceBundle is not ported, so
    /// every package currently gets CtSym.EMPTY (the upstream missing-key result).  No
    /// substitute attributes are invented (reported).
    fn get_ct_info(rd: &RelativeDirectory) -> CtSym {
        if rd.as_relative_path().get_path().is_empty() {
            return CtSym::empty();
        }
        CtSym::empty()
    }

    /// Java: public boolean isInJRT(FileObject fo).
    ///
    /// PORTING_RULES: the jrt FileSystem identity test becomes the JRTFileObject construction
    /// marker; the parameter is the concrete PathFileObject (Rust cannot downcast FileObject;
    /// registered, no upstream caller yet).
    pub fn is_in_jrt(&self, fo: &PathFileObject) -> bool {
        fo.is_jrt()
    }
}

#[cfg(test)]
mod tests {
    use super::{CtSym, JRTIndex};
    use crate::file::base_file_manager::BaseFileManager;
    use crate::file::base_file_manager_api::BaseFileManagerApi;
    use crate::file::path_file_object::PathFileObject;
    use crate::file::relative_path::RelativeDirectory;
    use crate::util::context::Context;
    use javac_fs::Path as FsPath;
    use javac_strings::JavaString;
    use std::path::PathBuf;
    use std::rc::Rc;

    fn js(s: &str) -> JavaString {
        JavaString::from(s)
    }

    /// Finds a JDK home with lib/modules: JAVA_HOME first, then the directory above the javac
    /// found on PATH (tests run on the developer machine, not in the compiler).
    fn baseline_java_home() -> Option<PathBuf> {
        if let Some(home) = std::env::var_os("JAVA_HOME") {
            let home = PathBuf::from(home);
            if home.join("lib").join("modules").is_file() {
                return Some(home);
            }
        }
        if let Some(paths) = std::env::var_os("PATH") {
            for dir in std::env::split_paths(&paths) {
                let javac = dir.join(if cfg!(windows) { "javac.exe" } else { "javac" });
                if javac.is_file()
                    && let Some(bin) = javac.parent()
                    && let Some(home) = bin.parent()
                    && home.join("lib").join("modules").is_file()
                {
                    return Some(home.to_path_buf());
                }
            }
        }
        None
    }

    fn fs_path(home: &std::path::Path) -> FsPath {
        FsPath::from_path_buf(home.to_path_buf())
    }

    #[test]
    fn root_entry_lists_module_roots() {
        let Some(home) = baseline_java_home() else {
            return;
        };
        let home = fs_path(&home);
        let index = JRTIndex::open(&home).expect("open the jrt: image");
        let root = RelativeDirectory::new(&js(""));
        let entry = index.get_entry(&root).expect("root entry");
        // Java: the /modules children are module directories; module-info.class files are the
        // only regular files at that level.
        assert!(entry.get_file("module-info.class").is_some());
        assert!(entry.get_file("no-such-file").is_none());
        assert!(entry.subdirs.contains(&RelativeDirectory::new(&js("java"))));
        let file_path = entry.get_file("module-info.class").expect("module-info");
        // PORTING_RULES: the jrt: virtual path is carried in a javac-fs Path; on Windows its
        // textual form uses '\', so the test normalizes the separator before comparing the
        // jrt-shaped path (the S3c file manager parses both forms).
        let text = file_path.to_java_string().replace('\\', "/");
        assert!(text.starts_with("/modules/"), "{text}");
        assert!(text.ends_with("/module-info.class"), "{text}");
    }

    #[test]
    fn package_entry_lists_files_and_subdirectories() {
        let Some(home) = baseline_java_home() else {
            return;
        };
        let home = fs_path(&home);
        let index = JRTIndex::open(&home).expect("open the jrt: image");
        let rd = RelativeDirectory::for_package(&js("java.lang"));
        let entry = index.get_entry(&rd).expect("java.lang entry");
        assert!(entry.get_file("Object.class").is_some());
        assert!(entry.get_file("String.class").is_some());
        let object = entry.get_file("Object.class").expect("Object.class");
        assert_eq!(
            object.to_java_string().replace('\\', "/"),
            "/modules/java.base/java/lang/Object.class"
        );
        // Nested packages of java.lang appear as subdirectories.
        assert!(
            entry
                .subdirs
                .contains(&RelativeDirectory::with_parent(&rd, &js("annotation")))
        );
        // The upstream Entry cache: the same RelativeDirectory yields the same Rc.
        let again = index.get_entry(&rd).expect("cached java.lang entry");
        assert!(Rc::ptr_eq(&entry, &again));
    }

    #[test]
    fn unknown_package_yields_an_empty_entry() {
        let Some(home) = baseline_java_home() else {
            return;
        };
        let home = fs_path(&home);
        let index = JRTIndex::open(&home).expect("open the jrt: image");
        let rd = RelativeDirectory::for_package(&js("no.such.package"));
        let entry = index.get_entry(&rd).expect("empty entry");
        assert!(entry.files.is_empty());
        assert!(entry.subdirs.is_empty());
    }

    #[test]
    fn ct_sym_is_empty_until_the_ct_resource_is_generated() {
        let Some(home) = baseline_java_home() else {
            return;
        };
        let home = fs_path(&home);
        let index = JRTIndex::open(&home).expect("open the jrt: image");
        let ct_sym = index
            .get_ct_sym(&js("java.lang"))
            .expect("getCtSym java.lang");
        assert_eq!(ct_sym, CtSym::empty());
        assert_eq!(ct_sym.to_string(), "CtSym[]");
        // The upstream toString layout for non-empty attributes.
        let full = CtSym {
            hidden: true,
            proprietary: true,
            min_profile: Some(js("compact1")),
        };
        assert_eq!(full.to_string(), "CtSym[hidden,proprietary,compact1]");
    }

    #[test]
    fn instances_are_cached_per_context_and_per_thread() {
        let Some(home) = baseline_java_home() else {
            return;
        };
        let home = fs_path(&home);
        let shared = JRTIndex::get_shared_instance(&home);
        assert!(Rc::ptr_eq(&shared, &JRTIndex::get_shared_instance(&home)));
        assert!(JRTIndex::is_available(&home));

        let mut context = Context::new();
        let first = JRTIndex::instance(&mut context, &home);
        let second = JRTIndex::instance(&mut context, &home);
        assert!(Rc::ptr_eq(&first, &second));
        let mut other_context = Context::new();
        let other = JRTIndex::instance(&mut other_context, &home);
        assert!(!Rc::ptr_eq(&first, &other));
    }

    #[test]
    fn is_in_jrt_uses_the_jrt_file_object_kind() {
        let manager: Rc<dyn BaseFileManagerApi> = Rc::new(BaseFileManager::new(
            None,
            FsPath::from_path_buf(std::path::PathBuf::from(".")),
        ));
        let path = FsPath::new("/modules/java.base/java/lang/Object.class").expect("path");
        let jrt_file = PathFileObject::for_jrt_path(manager.clone(), &path);
        let simple = PathFileObject::for_simple_path(manager, &path, &path);
        let Some(home) = baseline_java_home() else {
            return;
        };
        let index = JRTIndex::open(&fs_path(&home)).expect("open the jrt: image");
        assert!(index.is_in_jrt(&jrt_file));
        assert!(!index.is_in_jrt(&simple));
    }

    #[test]
    fn missing_image_is_not_available() {
        let missing = FsPath::from_path_buf(std::env::temp_dir().join("no-such-jdk-home"));
        assert!(!JRTIndex::is_available(&missing));
        assert!(JRTIndex::open(&missing).is_err());
    }
}
