/// A read-only resource bundle table: resource key -> message template.
pub type ResourceBundleTable = &'static crate::resources::message_table::MessageTable;

/// One resource bundle: the candidate table chain (most specific locale first,
/// base bundle last), modelling the ResourceBundle parent chain so that a key
/// missing from a translation falls back to the base bundle.
#[derive(Debug, Clone, Default)]
pub struct ResourceBundle {
    pub tables: Vec<ResourceBundleTable>,
}

impl ResourceBundle {
    /// Builds a bundle from its candidate chain.
    pub fn new(tables: Vec<ResourceBundleTable>) -> ResourceBundle {
        ResourceBundle { tables }
    }
}

/// Minimal mapping of java.util.Locale (adapter; registered in porting adapter
/// section 9): the locale tag, e.g. "en", "zh_CN", "en_US".
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Locale {
    tag: String,
}

impl Locale {
    /// Java: new Locale(language, country, variant) style construction from a tag.
    pub fn new(tag: impl Into<String>) -> Locale {
        Locale { tag: tag.into() }
    }

    /// Java: Locale.getDefault() -- detected from LC_ALL/LC_MESSAGES/LANG
    /// (the JVM property source equivalent); on Windows the user UI language
    /// is used (the JVM's user.language source). C/POSIX and unknown languages
    /// fall back to "en". Hyphen separators are normalized to "_".
    pub fn default_locale() -> Locale {
        // Unit tests must be independent of the host UI language.
        if cfg!(test) {
            return Locale::new("en");
        }
        let override_locale = DEFAULT_LOCALE_OVERRIDE
            .lock()
            .ok()
            .and_then(|guard| guard.as_ref().cloned());
        if let Some(locale) = override_locale {
            return locale;
        }
        ENVIRONMENT_DEFAULT_LOCALE
            .get_or_init(detect_environment_locale)
            .clone()
    }

    /// The locale tag (adapter representation).
    pub fn get_tag(&self) -> &str {
        &self.tag
    }

    /// Java: Locale.getLanguage()
    pub fn get_language(&self) -> &str {
        self.tag.split(['_', '-']).next().unwrap_or("")
    }

    /// Java: Locale.getCountry()
    pub fn get_country(&self) -> &str {
        let mut parts = self.tag.split(['_', '-']);
        parts.next();
        parts.next().unwrap_or("")
    }
}

/// Process-wide default locale override installed by the CLI after parsing
/// `-J-Duser.language`/`-J-Duser.country` (Java: the JVM properties).
static DEFAULT_LOCALE_OVERRIDE: Mutex<Option<Locale>> = Mutex::new(None);

/// Locale detected from the environment (`LC_ALL`/`LC_MESSAGES`/`LANG`, or
/// the Windows UI language), cached for the process. Detection is stable for a
/// compiler run, but it used to run on every `JavacMessages` construction.
static ENVIRONMENT_DEFAULT_LOCALE: std::sync::OnceLock<Locale> = std::sync::OnceLock::new();

/// Java: Locale.getDefault() environment detection, cached by
/// `ENVIRONMENT_DEFAULT_LOCALE`.
fn detect_environment_locale() -> Locale {
    for variable in ["LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(value) = std::env::var(variable) {
            if value.is_empty() {
                continue;
            }
            let tag = value
                .split('.')
                .next()
                .unwrap_or("")
                .split('@')
                .next()
                .unwrap_or("");
            if tag.is_empty() || tag == "C" || tag == "POSIX" {
                return Locale::new("en");
            }
            let tag = tag.replace('-', "_");
            return Locale::new(normalize_locale_tag(&tag));
        }
    }
    if let Some(tag) = sys_locale::get_locale() {
        return Locale::new(normalize_locale_tag(&tag));
    }
    Locale::new("en")
}

/// Sets the process default locale (used by the CLI launcher).
pub fn set_default_locale(locale: Locale) {
    if let Ok(mut guard) = DEFAULT_LOCALE_OVERRIDE.lock() {
        *guard = Some(locale);
    }
}

/// Candidate locale tags in preference order: the BCP 47 likely-subtags form
/// first, then the ResourceBundle truncation chain.
fn locale_candidates(tag: &str) -> Vec<String> {
    let normalized = tag.replace('-', "_");
    // CLDR likely-subtags data supplies the region/script a bare tag implies.
    let resolved = LIKELY_SUBTAGS
        .get(&normalized)
        .map(str::to_string)
        .unwrap_or(normalized);
    let mut candidates: Vec<String> = Vec::new();
    // BCP 47 language[_script][_region]: try the full tag, then the script,
    // then the region, then the bare language (Java ResourceBundle order).
    let langid: Option<unic_langid::LanguageIdentifier> =
        resolved.replace('_', "-").parse().ok();
    let (language, script, region) = match &langid {
        Some(id) => (
            id.language.to_string(),
            id.script.map(|script| script.to_string()),
            id.region.map(|region| region.to_string()),
        ),
        None => (
            resolved.split('_').next().unwrap_or("").to_string(),
            None,
            None,
        ),
    };
    if let (Some(script), Some(region)) = (&script, &region) {
        candidates.push(format!("{language}_{script}_{region}"));
    }
    if let Some(script) = &script {
        candidates.push(format!("{language}_{script}"));
    }
    if let Some(region) = &region {
        candidates.push(format!("{language}_{region}"));
    }
    candidates.push(language);
    candidates
}

/// Normalizes a language tag to an installed locale table name (en / ja /
/// zh_CN / zh_Hant); other languages keep only their language part.
fn normalize_locale_tag(tag: &str) -> String {
    for candidate in locale_candidates(tag) {
        if SUPPORTED_LOCALES.iter().any(|locale| *locale == candidate) {
            return candidate;
        }
    }
    let normalized = tag.replace('-', "_");
    normalized.split('_').next().unwrap_or("").to_string()
}


impl Default for Locale {
    fn default() -> Locale {
        Locale::default_locale()
    }
}

impl fmt::Display for Locale {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.tag)
    }
}

/// Java: JavacMessages.ResourceBundleHelper -- provides the resource bundle for
/// a locale.
pub trait ResourceBundleHelper {
    /// Java: getResourceBundle(Locale locale); None is the Rust equivalent of
    /// throwing MissingResourceException.
    fn get_resource_bundle(&self, locale: &Locale) -> Option<ResourceBundle>;
}

/// The default helper: resolves a bundle name against the built-in tables.
struct NamedBundle {
    bundle_name: String,
}

impl ResourceBundleHelper for NamedBundle {
    fn get_resource_bundle(&self, locale: &Locale) -> Option<ResourceBundle> {
        lookup_bundle(&self.bundle_name, locale)
    }
}

/// Resolves a bundle name (and locale) to a ResourceBundle candidate chain.
///
/// Java: ResourceBundle.getBundle(bundleName, locale). Locale matching follows
/// ResourceBundle semantics: the chain walks the locale from the most specific
/// form down to the language and finally the base bundle, so a missing key in a
/// translation falls back to the base text.
fn lookup_bundle(bundle_name: &str, locale: &Locale) -> Option<ResourceBundle> {
    let (base, variants): (ResourceBundleTable, &[(&str, ResourceBundleTable)]) = match bundle_name
    {
        DEFAULT_BUNDLE_NAME => (&COMPILER_MESSAGES, COMPILER_VARIANTS),
        LAUNCHER_BUNDLE_NAME => (&LAUNCHER_MESSAGES, LAUNCHER_VARIANTS),
        JAVAC_BUNDLE_NAME => (&JAVAC_MESSAGES, JAVAC_VARIANTS),
        _ => return None,
    };
    let mut tables = Vec::new();
    for candidate in locale_candidates(locale.get_tag()) {
        if let Some((_, table)) = variants
            .iter()
            .find(|(variant, _)| *variant == candidate.as_str())
        {
            tables.push(*table);
        }
    }
    tables.push(base);
    Some(ResourceBundle::new(tables))
}

/// Java: public class JavacMessages implements Messages.
///
/// the bundle cache is a RefCell because upstream mutates the
/// cache from non-mutating-looking methods (SoftReference cache); this is a
/// registered interior-mutability adapter for the diagnostic layer.
pub struct JavacMessages {
    bundle_cache: RefCell<HashMap<Locale, Vec<ResourceBundle>>>,
    bundle_helpers: Vec<Box<dyn ResourceBundleHelper>>,
    current_locale: Locale,
    current_bundles: RefCell<Option<Vec<ResourceBundle>>>,
}

impl JavacMessages {
    /// Java: JavacMessages.instance(Context context)
    pub fn instance(context: &mut Context) -> Rc<JavacMessages> {
        if let Some(instance) = context.get::<JavacMessages>() {
            return instance;
        }
        // REGISTERED D5: the upstream Context constructor also initializes
        // Options and the DiagnosticFormatter; that hook is not ported here.
        let instance = Rc::new(JavacMessages::new(DEFAULT_BUNDLE_NAME));
        context.put(instance.clone());
        instance
    }

    /// Java: JavacMessages(String bundleName)
    pub fn new(bundle_name: &str) -> JavacMessages {
        JavacMessages::with_locale(bundle_name, None)
    }

    /// Java: JavacMessages(String bundleName, Locale locale)
    pub fn with_locale(bundle_name: &str, locale: Option<Locale>) -> JavacMessages {
        let mut messages = JavacMessages {
            bundle_cache: RefCell::new(HashMap::new()),
            bundle_helpers: Vec::new(),
            current_locale: Locale::default_locale(),
            current_bundles: RefCell::new(None),
        };
        messages.add(bundle_name);
        messages.set_current_locale(locale);
        messages
    }

    /// Java: JavacMessages()
    pub fn default_messages() -> JavacMessages {
        JavacMessages::new(DEFAULT_BUNDLE_NAME)
    }

    /// Java: Locale getCurrentLocale()
    pub fn get_current_locale(&self) -> &Locale {
        &self.current_locale
    }

    /// Java: void setCurrentLocale(Locale locale)
    pub fn set_current_locale(&mut self, locale: Option<Locale>) {
        let locale = locale.unwrap_or_else(Locale::default_locale);
        let bundles = self.get_bundles(&locale);
        *self.current_bundles.borrow_mut() = Some(bundles);
        self.current_locale = locale;
    }

    /// Java: void add(String bundleName)
    pub fn add(&mut self, bundle_name: &str) {
        self.add_helper(Box::new(NamedBundle {
            bundle_name: bundle_name.to_string(),
        }));
    }

    /// Java: void add(ResourceBundleHelper ma) -- the Java overload is mapped to
    /// a distinct Rust method name because Rust has no overloading
    /// ().
    pub fn add_helper(&mut self, helper: Box<dyn ResourceBundleHelper>) {
        // Java: bundleHelpers = bundleHelpers.prepend(ma) -- the last added
        // helper is searched first.
        self.bundle_helpers.insert(0, helper);
        self.bundle_cache.borrow_mut().clear();
        *self.current_bundles.borrow_mut() = None;
    }

    /// Java: List<ResourceBundle> getBundles(Locale locale)
    pub fn get_bundles(&self, locale: &Locale) -> Vec<ResourceBundle> {
        if &self.current_locale == locale
            && let Some(bundles) = self.current_bundles.borrow().as_ref()
        {
            return bundles.clone();
        }
        let cached = self.bundle_cache.borrow().get(locale).cloned();
        if let Some(cached) = cached {
            return cached;
        }
        let mut bundles = Vec::new();
        for helper in &self.bundle_helpers {
            match helper.get_resource_bundle(locale) {
                Some(bundle) => bundles.push(bundle),
                // Java: catch MissingResourceException -> new InternalError(...)
                None => panic!("Cannot find requested resource bundle for locale {locale}"),
            }
        }
        self.bundle_cache
            .borrow_mut()
            .insert(locale.clone(), bundles.clone());
        bundles
    }

    /// Java: String getLocalizedString(String key, Object... args)
    pub fn get_localized_string(&self, key: &str, args: &[String]) -> String {
        self.get_localized_string_for(None, key, args)
    }

    /// Java: String getLocalizedString(Locale l, String key, Object... args)
    /// (the Locale overload gets a distinct Rust name, ).
    pub fn get_localized_string_for(
        &self,
        locale: Option<&Locale>,
        key: &str,
        args: &[String],
    ) -> String {
        let locale = locale
            .cloned()
            .unwrap_or_else(|| self.get_current_locale().clone());
        let bundles = self.get_bundles(&locale);
        get_localized_string_in(&bundles, key, args)
    }

    /// Java: static ResourceBundle getDefaultBundle()
    pub fn get_default_bundle() -> ResourceBundle {
        lookup_bundle(DEFAULT_BUNDLE_NAME, &Locale::default_locale())
            .expect("Fatal: Resource for compiler is missing")
    }

    /// Java: static String getDefaultLocalizedString(String key, Object... args)
    pub fn get_default_localized_string(key: &str, args: &[String]) -> String {
        get_localized_string_in(&[JavacMessages::get_default_bundle()], key, args)
    }
}

impl Messages for JavacMessages {
    fn add(&mut self, bundle_name: &str) {
        JavacMessages::add(self, bundle_name);
    }

    fn get_localized_string(&self, locale: Option<&Locale>, key: &str, args: &[String]) -> String {
        self.get_localized_string_for(locale, key, args)
    }
}

/// Java: private static String getLocalizedString(List<ResourceBundle> bundles,
/// String key, Object... args)
fn get_localized_string_in(bundles: &[ResourceBundle], key: &str, args: &[String]) -> String {
    let mut message: Option<&'static str> = None;
    'bundles: for bundle in bundles {
        for table in &bundle.tables {
            if let Some(template) = table.get(key) {
                message = Some(template);
                break 'bundles;
            }
        }
    }
    let template = match message {
        // javac's .properties parser consumes the separator whitespace and the
        // optional '=' after it; the generator kept a leading '=' for keys
        // written as "key =\". Those values are not part of the message.
        Some(template) => template.strip_prefix('=').unwrap_or(template).to_string(),
        None => format!(
            "compiler message file broken: key={key} arguments={{0}}, {{1}}, {{2}}, {{3}}, {{4}}, {{5}}, {{6}}, {{7}}"
        ),
    };
    message_format::format(&template, args)
}

