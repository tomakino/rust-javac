//! Generates the locale bundle tables from the file names under
//! `resources/l10n`: `<bundle>_<locale>.properties` becomes a variant entry,
//! so adding a locale means adding files, not editing code.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let dir = Path::new(&manifest).join("resources").join("l10n");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut bundles: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();
    let mut locales: Vec<String> = Vec::new();
    for entry in fs::read_dir(&dir).expect("read l10n directory").flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        let Some(stem) = name.strip_suffix(".properties") else { continue };
        let Some((bundle, locale)) = stem.split_once('_') else { continue };
        if locale.is_empty() { continue; }
        bundles
            .entry(bundle.to_string())
            .or_default()
            .push((locale.to_string(), name.clone()));
        locales.push(locale.to_string());
    }
    locales.sort();
    locales.dedup();
    for entries in bundles.values_mut() {
        entries.sort();
    }

    let mut out = String::new();
    out.push_str("// @generated by build.rs from resources/l10n file names.\n");
    out.push_str("pub static SUPPORTED_LOCALES: &[&str] = &[\n");
    for locale in &locales {
        out.push_str(&format!("    {:?},\n", locale));
    }
    out.push_str("];\n");
    for (bundle, entries) in &bundles {
        let upper = bundle.to_uppercase();
        for (locale, file) in entries {
            let ident = locale.to_uppercase();
            out.push_str(&format!(
                "pub static {upper}_{ident}: crate::resources::message_table::MessageTable =\n    crate::resources::message_table::MessageTable::new(include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/resources/l10n/{file}\")));\n"
            ));
        }
        out.push_str(&format!(
            "pub static {upper}_VARIANTS: &[(&str, &crate::resources::message_table::MessageTable)] = &[\n"
        ));
        for (locale, _) in entries {
            let ident = locale.to_uppercase();
            out.push_str(&format!("    ({:?}, &{upper}_{ident}),\n", locale));
        }
        out.push_str("];\n");
    }
    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("locales.rs");
    fs::write(&dest, out).expect("write generated locales");
}