//! Development tooling for rust-javac.
//!
//! Commands:
//!   cargo xtask gen-resources   - generate crates/javac-core/src/resources/
//!                                 compiler_properties.rs (typed diagnostic
//!                                 accessors) from upstream javac resources, and
//!                                 verify them against javac source call sites
//!   cargo xtask gen-manifest    - generate docs/PORTING_MANIFEST.md (Java file
//!                                 to Rust file mapping and porting status)
//!   cargo xtask gen-unicode     - regenerate the Unicode data tables from the
//!                                 running JDK 17 (requires a JDK on PATH)
//!   cargo xtask audit-porting   - method-level porting coverage audit
//!                                 (PORTING_RULES §19; --strict fails on gaps)
//!
//! The tools read the upstream reference tree from reference/jdk17u (not part of
//! the repository; see docs/PLAN.md).

mod audit_porting;
mod gen_resources;
mod properties;

use std::fs;
use std::path::{Path, PathBuf};

const REFERENCE: &str = "reference/jdk17u/src/jdk.compiler/share/classes";
const CORE_SRC: &str = "crates/javac-core/src";

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let cmd = args.first().map(String::as_str).unwrap_or("");
    let result = match cmd {
        "gen-resources" => gen_resources::generate_and_verify(),
        "gen-manifest" => gen_manifest(),
        "gen-unicode" => gen_unicode(),
        "audit-porting" => audit_porting::run(&args[1..]),
        _ => {
            eprintln!("usage: cargo xtask <gen-resources|gen-manifest|gen-unicode|audit-porting>");
            std::process::exit(2);
        }
    };
    if let Err(e) = result {
        eprintln!("xtask: {e}");
        std::process::exit(1);
    }
}

fn gen_unicode() -> Result<(), String> {
    let out = "crates/javac-unicode/src/generated.rs";
    let status = std::process::Command::new("java")
        .args(["tools/gen-unicode/GenUnicode.java", out])
        .status()
        .map_err(|e| format!("failed to run java (JDK 17 required): {e}"))?;
    if !status.success() {
        return Err(format!("GenUnicode.java failed: {status}"));
    }
    Ok(())
}

fn gen_manifest() -> Result<(), String> {
    let root = Path::new(REFERENCE);
    let mut rows: Vec<(String, String, bool)> = Vec::new();
    walk_java(root, root, &mut rows)?;
    rows.sort();
    let mut out = String::new();
    out.push_str("# Porting manifest\n\n");
    out.push_str("Generated by the gen-manifest xtask. Baseline: 982d53c (jdk-17.0.19-ga).\n\n");
    out.push_str("| Java source | Rust file | Ported |\n|---|---|---|\n");
    let mut ported = 0;
    for (rel, rust, exists) in &rows {
        if *exists {
            ported += 1;
        }
        out.push_str(&format!(
            "| {} | {} | {} |\n",
            rel,
            rust,
            if *exists { "yes" } else { "" }
        ));
    }
    out.push_str(&format!(
        "\nTotal: {} Java files, {} mapped Rust files present.\n",
        rows.len(),
        ported
    ));
    fs::write("docs/PORTING_MANIFEST.md", out).map_err(|e| format!("write manifest: {e}"))?;
    println!("gen-manifest: {} Java files, {} ported", rows.len(), ported);
    Ok(())
}

fn walk_java(root: &Path, dir: &Path, rows: &mut Vec<(String, String, bool)>) -> Result<(), String> {
    let entries = fs::read_dir(dir).map_err(|e| format!("read {dir:?}: {e}"))?;
    let mut paths: Vec<PathBuf> = Vec::new();
    for e in entries {
        let e = e.map_err(|e| format!("read entry: {e}"))?;
        paths.push(e.path());
    }
    paths.sort();
    for p in paths {
        if p.is_dir() {
            walk_java(root, &p, rows)?;
        } else if p.extension().map(|e| e == "java").unwrap_or(false) {
            let rel = p.strip_prefix(root).map_err(|e| e.to_string())?;
            let rel_str = rel.to_string_lossy().replace('\\', "/");
            // Only com/sun/tools/javac is mapped today; com/sun/source interfaces
            // are planned for the API phase and are reported separately later.
            if !rel_str.starts_with("com/sun/tools/javac/") {
                continue;
            }
            let rust = java_to_rust_path(&rel_str)?;
            let exists = Path::new(CORE_SRC).join(&rust).is_file();
            rows.push((rel_str, rust, exists));
        }
    }
    Ok(())
}

fn java_to_rust_path(rel: &str) -> Result<String, String> {
    // com/sun/tools/javac/util/Context.java -> util/context.rs
    // com/sun/tools/javac/Main.java        -> root/main.rs
    // package-info files are clipped (documentation only) -> (skipped)
    let parts: Vec<&str> = rel.split('/').collect();
    if parts.len() < 5
        || parts[0] != "com"
        || parts[1] != "sun"
        || parts[2] != "tools"
        || parts[3] != "javac"
    {
        return Err(format!("unexpected path: {rel}"));
    }
    let file = *parts.last().unwrap();
    let stem = file.strip_suffix(".java").ok_or("not a java file")?;
    if stem == "package-info" {
        return Ok("(skipped: package-info)".to_string());
    }
    let snake = to_snake_case(stem);
    if parts.len() == 5 {
        // top-level file (com.sun.tools.javac.Main)
        Ok(format!("root/{snake}.rs"))
    } else {
        let pkg = parts[4];
        Ok(format!("{pkg}/{snake}.rs"))
    }
}

fn to_snake_case(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            for lc in c.to_lowercase() {
                out.push(lc);
            }
        } else {
            out.push(c);
        }
    }
    out
}
